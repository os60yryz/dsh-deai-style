const J = (a) => a.join("\n");
const rows = [];
function P(tag, text, expect) {
  const r = lint(text);
  const fw = r.hits.filter((h) => h.kind === "metric" && h.evidence === "format").reduce((s, h) => s + h.sev * h.count, 0);
  rows.push({ tag, expect, chars: r.chars, score: r.score, band: r.band, an: r.analyzed, rw: r.ruleWeight, mw: r.metricWeight, fw: Math.round(fw * 100) / 100, hits: r.hits.map((h) => `${h.id}(${h.sev})x${h.count}`).join(",") });
}

