const TOOL_HINT = (toolName) =>
  `需要自检时，可以对草稿调用工具 \`${toolName}\` 打分；分数高于 35 时，按命中项重写，只改风格不改事实。`;

export function renderPrompt({ level = "strict", extraRules = "", toolName = null } = {}) {
  if (level === "off") return "";
  // soft 档拿全部 CORE（原先 slice(0,10) 会连第 10 条一起丢掉，只剩 9 条编号项）
  const body = level === "strict" ? [...CORE, ...STRICT_EXTRA] : [...CORE];
  const lines = ["## 去 AI 腔表达风格", "", ...body];
  if (toolName) lines.push("", TOOL_HINT(toolName));
  if (extraRules && extraRules.trim()) lines.push("", "补充要求：", extraRules.trim());
  return lines.join("\n");
}
